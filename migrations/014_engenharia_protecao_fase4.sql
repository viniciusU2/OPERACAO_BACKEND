    id_ied_ensaio INT NOT NULL AUTO_INCREMENT,
    id_ied INT NOT NULL,
    numero INT NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'ROTINA',
    status VARCHAR(20) NOT NULL DEFAULT 'PLANEJADO',
    descricao TEXT NULL,
    data_prevista DATE NULL,
    data_execucao DATE NULL,
    id_os INT NULL,
    id_usuario_executor INT NULL,
    instrumentos TEXT NULL,
    resultado TEXT NULL,
    observacoes TEXT NULL,
    versao INT NOT NULL DEFAULT 1,
    id_usuario_criacao INT NOT NULL,
    id_usuario_atualizacao INT NOT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id_ied_ensaio),
    UNIQUE KEY uq_ied_ensaio_numero (id_ied, numero),
    KEY ix_ied_ensaio_ied (id_ied),
    KEY ix_ied_ensaio_tipo (tipo),
    KEY ix_ied_ensaio_status (status),
    KEY ix_ied_ensaio_os (id_os),
    KEY ix_ied_ensaio_executor (id_usuario_executor),
    CONSTRAINT ck_ied_ensaio_tipo CHECK (tipo IN ('COMISSIONAMENTO','ACEITACAO','ROTINA','PERIODICO','POS_EVENTO','POS_REPARO','OUTRO')),
    CONSTRAINT ck_ied_ensaio_status CHECK (status IN ('PLANEJADO','EM_ANDAMENTO','APROVADO','REPROVADO','CANCELADO')),
    CONSTRAINT fk_ied_ensaio_ied FOREIGN KEY (id_ied) REFERENCES ied (id_ied) ON DELETE CASCADE,
