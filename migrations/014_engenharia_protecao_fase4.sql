-- --------------------------------------------------------------------------- --
-- Comunicação / IEC 61850
-- --------------------------------------------------------------------------- --

CREATE TABLE IF NOT EXISTS ied_interface_comunicacao (
    id_ied_interface_comunicacao INT NOT NULL AUTO_INCREMENT,
    id_ied INT NOT NULL,
    nome VARCHAR(60) NOT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'ETHERNET',
    meio VARCHAR(30) NULL,
    mac_address VARCHAR(32) NULL,
    endereco_ip VARCHAR(45) NULL,
    mascara VARCHAR(45) NULL,
    gateway VARCHAR(45) NULL,
    vlan VARCHAR(30) NULL,
    velocidade VARCHAR(20) NULL,
    conectada TINYINT(1) NOT NULL DEFAULT 1,
    descricao TEXT NULL,
    observacoes TEXT NULL,
    versao INT NOT NULL DEFAULT 1,
    id_usuario_criacao INT NOT NULL,
    id_usuario_atualizacao INT NOT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id_ied_interface_comunicacao),
    UNIQUE KEY uq_ied_interface_comunicacao_nome (id_ied, nome),
    KEY ix_ied_interface_comunicacao_ied (id_ied),
    KEY ix_ied_interface_comunicacao_tipo (tipo),
    CONSTRAINT ck_ied_interface_comunicacao_tipo CHECK (tipo IN ('ETHERNET','SERIAL','FIBRA_OPTICA','PROCESS_BUS','WIRELESS')),
    CONSTRAINT fk_ied_interface_comunicacao_ied FOREIGN KEY (id_ied) REFERENCES ied (id_ied) ON DELETE CASCADE,
    CONSTRAINT fk_ied_interface_comunicacao_usuario_criacao FOREIGN KEY (id_usuario_criacao) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ied_interface_comunicacao_usuario_atualizacao FOREIGN KEY (id_usuario_atualizacao) REFERENCES usuarios (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci;

CREATE TABLE IF NOT EXISTS ied_protocolo_comunicacao (
    id_ied_protocolo_comunicacao INT NOT NULL AUTO_INCREMENT,
    id_ied_interface_comunicacao INT NOT NULL,
    protocolo VARCHAR(40) NOT NULL,
    papel VARCHAR(20) NOT NULL DEFAULT 'SERVIDOR',
    porta VARCHAR(20) NULL,
    endereco_destino VARCHAR(60) NULL,
    habilitado TINYINT(1) NOT NULL DEFAULT 1,
    observacoes TEXT NULL,
    id_usuario_criacao INT NOT NULL,
    id_usuario_atualizacao INT NOT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id_ied_protocolo_comunicacao),
    UNIQUE KEY uq_ied_protocolo_comunicacao (id_ied_interface_comunicacao, protocolo, papel),
    KEY ix_ied_protocolo_comunicacao_interface (id_ied_interface_comunicacao),
    KEY ix_ied_protocolo_comunicacao_protocolo (protocolo),
    CONSTRAINT ck_ied_protocolo_comunicacao_protocolo CHECK (protocolo IN ('IEC61850_MMS','IEC61850_GOOSE','IEC61850_SV','DNP3','MODBUS_RTU','MODBUS_TCP','IEC60870_5_101','IEC60870_5_104','PROFIBUS','SNTP','NTP','PRP','HSR','OUTRO')),
    CONSTRAINT ck_ied_protocolo_comunicacao_papel CHECK (papel IN ('SERVIDOR','CLIENTE','PUBLICADOR','ASSINANTE','AMBOS')),
    CONSTRAINT fk_ied_protocolo_comunicacao_interface FOREIGN KEY (id_ied_interface_comunicacao) REFERENCES ied_interface_comunicacao (id_ied_interface_comunicacao) ON DELETE CASCADE,
    CONSTRAINT fk_ied_protocolo_comunicacao_usuario_criacao FOREIGN KEY (id_usuario_criacao) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ied_protocolo_comunicacao_usuario_atualizacao FOREIGN KEY (id_usuario_atualizacao) REFERENCES usuarios (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci;

