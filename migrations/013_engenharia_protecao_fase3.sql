-- ENGVI - Engenharia de Proteção, Controle e Automação
-- Fase 3: gestão de alterações (solicitação -> aprovação -> implantação -> validação)
-- e comparador de configurações (sem tabela própria: compara grupos/configurações).
-- Idempotente: pode ser reaplicada com segurança.

CREATE TABLE IF NOT EXISTS solicitacao_alteracao (
    id_solicitacao_alteracao INT NOT NULL AUTO_INCREMENT,
    numero INT NOT NULL,
    id_ied INT NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'AJUSTE',
    prioridade VARCHAR(20) NOT NULL DEFAULT 'MEDIA',
    status VARCHAR(30) NOT NULL DEFAULT 'RASCUNHO',
    id_configuracao_origem INT NULL,
    id_configuracao_resultante INT NULL,
    id_grupo_ajuste INT NULL,
    id_os INT NULL,
    justificativa TEXT NULL,
    observacoes TEXT NULL,
    data_necessidade DATE NULL,
    data_implantacao DATE NULL,
    data_validacao DATE NULL,
    resultado_validacao VARCHAR(20) NULL,
    id_usuario_solicitante INT NOT NULL,
    id_usuario_aprovador INT NULL,
    id_usuario_validador INT NULL,
    versao INT NOT NULL DEFAULT 1,
    id_usuario_criacao INT NOT NULL,
    id_usuario_atualizacao INT NOT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id_solicitacao_alteracao),
    UNIQUE KEY uq_solicitacao_alteracao_numero (numero),
    KEY ix_solicitacao_alteracao_ied (id_ied),
    KEY ix_solicitacao_alteracao_status (status),
    KEY ix_solicitacao_alteracao_tipo (tipo),
    KEY ix_solicitacao_alteracao_prioridade (prioridade),
    KEY ix_solicitacao_alteracao_ied_status (id_ied, status),
    KEY ix_solicitacao_alteracao_config_origem (id_configuracao_origem),
    KEY ix_solicitacao_alteracao_config_resultante (id_configuracao_resultante),
    KEY ix_solicitacao_alteracao_grupo (id_grupo_ajuste),
    KEY ix_solicitacao_alteracao_os (id_os),
    KEY ix_solicitacao_alteracao_solicitante (id_usuario_solicitante),
    CONSTRAINT ck_solicitacao_alteracao_tipo CHECK (tipo IN ('AJUSTE','FIRMWARE','HARDWARE','COMUNICACAO','CORRECAO','OUTRO')),
    CONSTRAINT ck_solicitacao_alteracao_prioridade CHECK (prioridade IN ('BAIXA','MEDIA','ALTA','CRITICA')),
    CONSTRAINT ck_solicitacao_alteracao_status CHECK (status IN ('RASCUNHO','SUBMETIDA','APROVADA','REJEITADA','IMPLANTADA','VALIDADA','NAO_VALIDADA','CANCELADA')),
    CONSTRAINT ck_solicitacao_alteracao_resultado CHECK (resultado_validacao IS NULL OR resultado_validacao IN ('APROVADO','REPROVADO')),
    CONSTRAINT fk_solicitacao_alteracao_ied FOREIGN KEY (id_ied) REFERENCES ied (id_ied) ON DELETE CASCADE,
    CONSTRAINT fk_solicitacao_alteracao_config_origem FOREIGN KEY (id_configuracao_origem) REFERENCES ied_configuracao (id_ied_configuracao) ON DELETE SET NULL,
    CONSTRAINT fk_solicitacao_alteracao_config_resultante FOREIGN KEY (id_configuracao_resultante) REFERENCES ied_configuracao (id_ied_configuracao) ON DELETE SET NULL,
    CONSTRAINT fk_solicitacao_alteracao_grupo FOREIGN KEY (id_grupo_ajuste) REFERENCES ied_grupo_ajuste (id_ied_grupo_ajuste) ON DELETE SET NULL,
    CONSTRAINT fk_solicitacao_alteracao_os FOREIGN KEY (id_os) REFERENCES ordem_servico (id_os) ON DELETE SET NULL,
    CONSTRAINT fk_solicitacao_alteracao_solicitante FOREIGN KEY (id_usuario_solicitante) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitacao_alteracao_aprovador FOREIGN KEY (id_usuario_aprovador) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_solicitacao_alteracao_validador FOREIGN KEY (id_usuario_validador) REFERENCES usuarios (id) ON DELETE SET NULL,
    CONSTRAINT fk_solicitacao_alteracao_usuario_criacao FOREIGN KEY (id_usuario_criacao) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_solicitacao_alteracao_usuario_atualizacao FOREIGN KEY (id_usuario_atualizacao) REFERENCES usuarios (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci;

CREATE TABLE IF NOT EXISTS alteracao_item (
    id_alteracao_item INT NOT NULL AUTO_INCREMENT,
    id_solicitacao_alteracao INT NOT NULL,
    id_parametro_definicao INT NOT NULL,
    valor_atual VARCHAR(255) NULL,
    valor_proposto VARCHAR(255) NULL,
    observacoes TEXT NULL,
    id_usuario_criacao INT NOT NULL,
    id_usuario_atualizacao INT NOT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id_alteracao_item),
    UNIQUE KEY uq_alteracao_item_parametro (id_solicitacao_alteracao, id_parametro_definicao),
    KEY ix_alteracao_item_solicitacao (id_solicitacao_alteracao),
    KEY ix_alteracao_item_parametro (id_parametro_definicao),
    CONSTRAINT fk_alteracao_item_solicitacao FOREIGN KEY (id_solicitacao_alteracao) REFERENCES solicitacao_alteracao (id_solicitacao_alteracao) ON DELETE CASCADE,
    CONSTRAINT fk_alteracao_item_parametro FOREIGN KEY (id_parametro_definicao) REFERENCES parametro_definicao (id_parametro_definicao) ON DELETE RESTRICT,
    CONSTRAINT fk_alteracao_item_usuario_criacao FOREIGN KEY (id_usuario_criacao) REFERENCES usuarios (id) ON DELETE RESTRICT,
    CONSTRAINT fk_alteracao_item_usuario_atualizacao FOREIGN KEY (id_usuario_atualizacao) REFERENCES usuarios (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci;

CREATE TABLE IF NOT EXISTS alteracao_historico (
    id_alteracao_historico INT NOT NULL AUTO_INCREMENT,
    id_solicitacao_alteracao INT NOT NULL,
    acao VARCHAR(30) NOT NULL,
    status_anterior VARCHAR(30) NULL,
    status_novo VARCHAR(30) NULL,
    comentario TEXT NULL,
    id_usuario INT NOT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_alteracao_historico),
    KEY ix_alteracao_historico_solicitacao (id_solicitacao_alteracao),
    CONSTRAINT ck_alteracao_historico_acao CHECK (acao IN ('CRIACAO','ATUALIZACAO','SUBMISSAO','APROVACAO','REJEICAO','IMPLANTACAO','VALIDACAO','REJEICAO_VALIDACAO','CANCELAMENTO')),
    CONSTRAINT fk_alteracao_historico_solicitacao FOREIGN KEY (id_solicitacao_alteracao) REFERENCES solicitacao_alteracao (id_solicitacao_alteracao) ON DELETE CASCADE,
    CONSTRAINT fk_alteracao_historico_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci;
