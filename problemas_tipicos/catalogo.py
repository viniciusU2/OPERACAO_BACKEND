"""Catálogo técnico de problemas típicos de subestações.

Cada item é um registro de REFERÊNCIA TÉCNICA (não é uma ocorrência real) e
alimenta a base de conhecimento do ENGVI. O conteúdo descreve hipóteses e
verificações; a confirmação depende de evidência de campo, do manual do
fabricante e dos ajustes aprovados da instalação.

Convenções:
- ``sistema``: sistema funcional da instalação.
- ``categoria``: grupo de equipamento (usado nos relatórios da seed).
- ``tipo_ativo``: nome do ``tipo_ativo`` existente; quando o nome não existir,
  a seed cria o catálogo com registro explícito no log.
- ``corretivas``: (tipo_acao, descricao, prioridade).
- ``preventivas``: descrições convertidas em ações com tipo ``PREVENCAO``.

Nenhum limite numérico de fabricante, código de alarme ou ajuste de proteção é
fixado aqui: valores dependem do projeto e devem seguir a documentação vigente.
"""

from __future__ import annotations

from typing import Iterable, Sequence

TiposCorretiva = Sequence[tuple[str, str, str]]


def p(
    codigo: str,
    titulo: str,
    categoria: str,
    sistema: str,
    tipo_ativo: str,
    criticidade: str,
    descricao: str,
    *,
    sintomas: Iterable[str],
    causas: Iterable[str],
    diagnostico: Iterable[str],
    corretivas: TiposCorretiva,
    preventivas: Iterable[str],
    alarmes: Iterable[str] = (),
    instrumentos: Iterable[str] = (),
    palavras_chave: Iterable[str] = (),
    modo_falha: str | None = None,
    efeito_falha: str | None = None,
    detectabilidade: str = "MEDIA",
    especialidade: str = "Manutenção de subestação",
    requer_desligamento: bool = False,
    risco: str = "MEDIO",
    condicao: str = "INDIFERENTE",
    equipe_especializada: bool = False,
    alerta: str | None = None,
    referencias: str | None = None,
) -> dict:
    acoes = [
        {
            "tipo_acao": tipo,
            "descricao": texto,
            "prioridade": prioridade,
            "prazo_recomendado": None,
        }
        for tipo, texto, prioridade in corretivas
    ]
    acoes += [
        {
            "tipo_acao": "PREVENCAO",
            "descricao": texto,
            "prioridade": "MEDIA",
            "prazo_recomendado": "Conforme plano de manutenção aprovado",
        }
        for texto in preventivas
    ]
    return {
        "codigo": codigo,
        "titulo": titulo,
        "categoria": categoria,
        "sistema": sistema,
        "tipo_ativo": tipo_ativo,
        "criticidade": criticidade,
        "descricao": descricao,
        "modo_falha": modo_falha,
        "efeito_falha": efeito_falha,
        "detectabilidade": detectabilidade,
        "especialidade": especialidade,
        "requer_desligamento": requer_desligamento,
        "risco_operacional": risco,
        "condicao_intervencao": condicao,
        "requer_equipe_especializada": equipe_especializada,
        "alerta_seguranca": alerta,
        "referencias_tecnicas": referencias,
        "sintomas": list(sintomas),
        "causas": list(causas),
        "metodos_deteccao": list(diagnostico),
        "alarmes": list(alarmes),
        "instrumentos": list(instrumentos),
        "palavras_chave": list(palavras_chave),
        "acoes_recomendadas": acoes,
    }


